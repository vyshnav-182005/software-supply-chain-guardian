"""Run: .venv/Scripts/python -m tests.test_python   (no network: uv and PyPI are faked)"""
import tempfile
from pathlib import Path

from app.agents import discovery, pydeps

COMPILED = """# This file was autogenerated by uv
click==8.1.7              # via flask
flask==2.0.1              # via -r requirements.txt
jinja2==3.1.6             # via flask
markupsafe==3.0.4         # via jinja2, werkzeug
requests==2.31.0          # via -r requirements.txt
werkzeug==3.1.9           # via flask
"""

if __name__ == "__main__":
    rows = pydeps.parse_compiled(COMPILED)
    assert ("flask", "2.0.1", [""]) in rows and ("markupsafe", "3.0.4", ["jinja2", "werkzeug"]) in rows

    d = Path(tempfile.mkdtemp())
    req = d / "requirements.txt"
    req.write_text("flask==2.0.1\nrequests>=2.25\n", encoding="utf-16")  # PowerShell pip freeze style

    def fake_compile(src, out, pyver=None):
        out.write_text(COMPILED, encoding="utf-8")
        return True, "", "uv pip compile requirements.txt --no-build"
    pydeps.compile_tree = fake_compile
    comps, edges = {}, set()
    p = pydeps.python_project("./requirements.txt", req, d, 0, comps, edges, discovery.requirements_project)
    assert p["status"] == "parsed" and p["component_count"] == 6 and p["lock_source"] == "generated"
    assert comps["pkg:pypi/flask@2.0.1"]["direct"] and not comps["pkg:pypi/jinja2@3.1.6"]["direct"]
    assert ("pkg:pypi/jinja2@3.1.6", "pkg:pypi/markupsafe@3.0.4", "runtime") in edges
    assert ("project:./requirements.txt", "pkg:pypi/flask@2.0.1", "runtime") in edges

    # fall back to the listed packages when resolution is impossible
    pydeps.compile_tree = lambda src, out, pyver=None: (False, "error: --no-build: foo has no wheels", "")
    comps2 = {}
    p2 = pydeps.python_project("./requirements.txt", req, d, 1, comps2, set(), discovery.requirements_project)
    assert p2["status"] == "partial" and len(comps2) == 2 and "source" in p2["notes"][-1]

    # fixes: edit a pin, add a constraint for a pulled-in package, undo both, keep UTF-16
    detail, prev = pydeps.edit_requirements(req, "Flask", "==2.3.3")
    assert prev == "==2.0.1" and "flask==2.3.3" in pydeps.read_text_any(req).lower()
    _, prev2 = pydeps.edit_requirements(req, "werkzeug", ">=3.0.6")
    assert prev2 is None and "werkzeug>=3.0.6" in pydeps.read_text_any(req)
    assert req.read_bytes()[:2] == b"\xff\xfe"                       # still UTF-16
    pydeps.undo_requirements(req, "werkzeug", None)
    pydeps.undo_requirements(req, "flask", "==2.0.1")
    assert pydeps.read_text_any(req).split() == ["flask==2.0.1", "requests>=2.25"]

    # safe version: skip versions with known high/critical advisories
    from packaging.version import Version
    pydeps._versions["jinja2"] = [Version(v) for v in ("3.1.3", "3.1.4", "3.1.5")]
    v, rej = pydeps.safe_version("jinja2", "3.1.2", "3.1.3", lambda n, ver: ["GHSA-x"] if ver == "3.1.3" else [])
    assert v == "3.1.4" and rej[0]["version"] == "3.1.3"
    print("python ok")
